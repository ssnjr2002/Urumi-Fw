describe("operatorJog/makeJog", () => {
    it("is byte-identical to Python make_jog for (160, 0, 80, 0) @ 1600 sps", () => {
        const pkts = makeJog([160, 0, 80, 0], 1600, 8000, 150_000_000, 50);
        expect(pkts.length).toBe(REF.length);
        for (let i = 0; i < REF.length; i++) {
            expect([...pkts[i]!]).toEqual(REF[i]!);
        }
    });

    it("produces 26-byte JOG packets (magic 0xAE)", () => {
        const pkts = makeJog([10, 0, 0, 0], 200, 1000, 150_000_000, 50);
        expect(pkts.length).toBeGreaterThan(0);
        for (const p of pkts) {
            expect(p.length).toBe(PACKET_SIZE);
            expect(p[0]).toBe(MAGIC_JOG);
        }
    });

    it("the last packet has the PATH_END flag set", () => {
        const pkts = makeJog([10, 0, 0, 0], 200, 1000, 150_000_000, 50);
        const last = pkts[pkts.length - 1]!;
        const flags = last[21];
        expect(flags! & 1).toBe(1); // bit 0 = PATH_END
    });

    it("the sum of all X deltas equals the requested steps", () => {
        const pkts = makeJog([160, -30, 80, 10], 1600, 8000, 150_000_000, 50);
        const totalX = pkts.reduce((n, p) => {
            const dv = new DataView(p.buffer, p.byteOffset, PACKET_SIZE);
            return n + dv.getInt32(1, true);
        }, 0);
        expect(totalX).toBe(160);
    });

    it("returns [] for a zero vector", () => {
        expect(makeJog([0, 0, 0, 0], 1600, 8000, 150_000_000)).toEqual([]);
    });
});